create table if not exists public.products (
    id bigint generated by default as identity primary key,
    name text not null,
    stock integer not null default 0 check (stock >= 0),
    price numeric(10, 2) not null check (price >= 0),
    category text,
    image_url text,
    description text
);

alter table public.products add column if not exists category text;
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists description text;

alter table public.products enable row level security;

drop policy if exists "Allow public product reads" on public.products;
create policy "Allow public product reads"
    on public.products
    for select
    to anon, authenticated
    using (true);

drop policy if exists "Allow public product writes" on public.products;
create policy "Allow public product writes"
    on public.products
    for all
    to anon, authenticated
    using (true)
    with check (true);

